from typing import List, Optional
from pydantic import BaseModel, Field


class Paper(BaseModel):
    """Normalized representation of an academic research paper."""
    title: str
    authors: List[str] = Field(default_factory=list)
    abstract: str = ""
    year: Optional[int] = None
    source: str  # e.g., 'arxiv', 'crossref', 'semantic_scholar'
    source_id: str  # e.g., 'arxiv:2303.08774', 'doi:10.1145/...'
    url: Optional[str] = None
    pdf_url: Optional[str] = None
    pdf_text_extracted: Optional[str] = None
    summary: Optional[str] = None
    bibtex: Optional[str] = None
    citation_key: Optional[str] = None


class ResearchPlan(BaseModel):
    """Plan generated by the Supervisor Agent."""
    topic: str
    subtopics: List[str] = Field(default_factory=list)
    search_queries: List[str] = Field(default_factory=list)
    notes: Optional[str] = None


class AgentState(BaseModel):
    """Complete workflow state passed between agents and serialized to Redis."""
    session_id: str
    topic: str
    plan: Optional[ResearchPlan] = None
    papers: List[Paper] = Field(default_factory=list)
    current_step: str = "initialized"
    status: str = "pending"  # 'pending', 'in_progress', 'completed', 'failed'
    error_messages: List[str] = Field(default_factory=list)
    introduction: Optional[str] = None
    conclusion: Optional[str] = None
    markdown_report: Optional[str] = None
    bibtex_content: Optional[str] = None
